/**
 * Seed data so the app is usable the moment it starts, before any backend
 * exists. The profiles are invented but the venues, districts and
 * classification spread are realistic for Zurich, which matters: a matching
 * algorithm tested against uniformly average fake users looks better than it is.
 */

const m = (...slots: Array<[number, TimeBlock]>): AvailabilityMask => maskFrom(slots);

type SeedInput = Omit<Player, 'createdAt'>;

function player(input: SeedInput): Player {
  return { ...input, createdAt: '2026-09-01T08:00:00.000Z' };
}

